export type IconName = keyof typeof icons;

export function normalizeIconName(name: string): string {
  // Quitar prefijos comunes como 'fa-', 'fas fa-', 'fab fa-', 'fa-solid fa-', etc.
  const clean = name
    .replace(/^fa[sbr]?\s+/, '')
    .replace(/^fa-/, '')
    .trim();

  // Mapeos de compatibilidad / alias
  if (clean === 'shield') return 'shield-alt';
  if (clean === 'xmark') return 'times';
  if (clean === 'cake') return 'cake-candles';
  return clean;
}
